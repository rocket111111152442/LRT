export function getPropertyBySlug(slug: string): Property | undefined {
  return properties.find((p) => p.slug === slug);
}

export function getFeaturedProperties(limit = 4): Property[] {
  return properties.filter((p) => p.featured).slice(0, limit);
}

export function getPropertiesByCommune(commune: string): Property[] {
  return properties.filter((p) => p.commune === commune);
}

export function getPropertiesByCanton(canton: string): Property[] {
  return properties.filter((p) => p.canton === canton);
}

export function getSimilarProperties(property: Property, limit = 3): Property[] {
  return properties
    .filter((p) => p.slug !== property.slug && p.canton === property.canton && p.type === property.type)
    .slice(0, limit)
    .concat(
      properties.filter((p) => p.slug !== property.slug && p.canton === property.canton && p.type !== property.type),
    )
    .slice(0, limit);
}
